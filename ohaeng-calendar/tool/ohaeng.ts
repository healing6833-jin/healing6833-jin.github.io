/** 양력 날짜(연·월·일) → 일진과 그날의 오행·오일 (매일 글과 같은 규칙) */
export function dayInfo(y: number, m: number, d: number) {
  const n = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(1949, 9, 1)) / 86400e3);
  const idx = ((n % 60) + 60) % 60;
  const s = idx % 10, b = idx % 12;
  const elIndex = Math.floor(s / 2);
  const el = ELEMENTS[elIndex];
  return { n, s, b, elIndex, el, yin: s % 2 === 1, oil: el.oils[n % el.oils.length], tip: el.tips[(n + 1) % el.tips.length],
    hanja: STEMS[s] + BRANCHES[b], kr: STEM_KR[s] + BRANCH_KR[b] };
}
